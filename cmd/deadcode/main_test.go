package main

import (
	"encoding/json"
	"os"
	"path/filepath"
	"testing"
)

func write(t *testing.T, dir, name, body string) {
	t.Helper()
	if err := os.WriteFile(filepath.Join(dir, name), []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestAnalyzeFindsUnused(t *testing.T) {
	dir := t.TempDir()
	write(t, dir, "a.go", `package p

func used() {}

func unused() {}

func caller() { used() }
`)
	write(t, dir, "a_test.go", `package p

import "testing"

func TestCaller(t *testing.T) { caller() }
`)
	findings, err := analyze(dir)
	if err != nil {
		t.Fatal(err)
	}
	if len(findings) != 1 || findings[0].Name != "unused" {
		t.Fatalf("findings = %#v, want unused", findings)
	}
}

